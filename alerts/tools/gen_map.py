"""Bake the raion map into alerts/wallpaper.lua (the block between -- MAP BEGIN and -- MAP END).

Usage: python3 alerts/tools/gen_map.py raions.geojson oblasts.geojson alerts/wallpaper.lua
Borders: https://neptun.in.ua/raions.geojson and https://neptun.in.ua/oblasts.geojson
(the same shapes the NEPTUN alerts API is keyed to).
Each region becomes a list of rectangles (horizontal pixel runs, merged when the
same run repeats on the next row). A 1 px gap is left on the right and bottom edge
of every raion, so the silhouette drawn underneath shows through as the border.
Oblast borders are baked separately and drawn on top in a lighter colour.
"""
import json, math, re, sys
from PIL import Image, ImageDraw

W, H = 268, 178  # map size in pixels
LON0, LON1, LAT0, LAT1 = 22.1, 40.25, 44.35, 52.4
K = math.cos(math.radians(48.4))

# Raions renamed after the shapes were drawn: old name -> current name
RENAMED = {
    "Новоград-Волинський район": "Звягельський район",
    "Новомосковський район": "Самарівський район",
    "Червоноградський район": "Шептицький район",
}
# Cities drawn on top of their oblast as their own regions
CITIES = {"м. київ": "м. Київ", "севастополь": "Севастополь"}
ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"


def px(lon, lat):
    w = (LON1 - LON0) * K
    s = min(W / w, H / (LAT1 - LAT0))
    return ((lon - LON0) * K * s, (LAT1 - lat) * s)


def enc(n):
    assert 0 <= n < 64 * 64
    return ALPHABET[n // 64] + ALPHABET[n % 64]


def polys(g):
    return g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]


def norm(s):
    return s.replace("’", "'").replace("ʼ", "'")


def draw(feats, value):
    img = Image.new("L", (W, H), 0)
    d = ImageDraw.Draw(img)
    for i, f in enumerate(feats, 1):
        for poly in polys(f["geometry"]):
            d.polygon([px(lon, lat) for lon, lat in poly[0]], fill=value(i, f))
            for hole in poly[1:]:
                d.polygon([px(lon, lat) for lon, lat in hole], fill=0)
    return img.load()


raions_src, oblasts_src, dst = sys.argv[1:4]
raions = json.load(open(raions_src, encoding="utf-8"))["features"]
oblasts = json.load(open(oblasts_src, encoding="utf-8"))["features"]
# Cities go last so they cover the hole in their oblast
oblasts.sort(key=lambda f: f["properties"]["key"] in CITIES)
oblast_names = [f["properties"].get("region") or f["properties"]["name"] for f in oblasts]
obl = draw(oblasts, lambda i, f: i)

# Regions: every raion, then the cities on top
regions = []  # (name, oblast index, feature)
for f in raions:
    regions.append([norm(RENAMED.get(f["properties"]["rayon"], f["properties"]["rayon"])), 0, f])
for f in oblasts:
    if f["properties"]["key"] in CITIES:
        regions.append([CITIES[f["properties"]["key"]], 0, f])
lab = draw([r[2] for r in regions], lambda i, f: i)
for i, r in enumerate(regions, 1):
    votes = {}
    for y in range(H):
        for x in range(W):
            if lab[x, y] == i and obl[x, y]:
                votes[obl[x, y]] = votes.get(obl[x, y], 0) + 1
    assert votes, "raion %s has no pixels" % r[0]
    r[1] = max(votes, key=votes.get)


def rects(inside):
    """Horizontal runs of pixels where inside(x, y), merged vertically into rectangles."""
    out, open_ = [], {}
    for y in range(H + 1):
        runs, x = [], 0
        while y < H and x < W:
            if inside(x, y):
                x0 = x
                while x < W and inside(x, y):
                    x += 1
                runs.append((x0, x))
            else:
                x += 1
        nxt = {}
        for r in runs:
            if r in open_:
                nxt[r] = open_.pop(r)
            else:
                nxt[r] = y
        for (x0, x1), y0 in open_.items():
            out.append((x0, y0, x1 - x0, y - y0))
        open_ = nxt
    return out


def at(img, x, y):
    return img[x, y] if 0 <= x < W and 0 <= y < H else 0


def pack(rs):
    return "".join(enc(v) for r in rs for v in r)


lines = ["-- MAP BEGIN (generated by tools/gen_map.py)", "local MAP_W, MAP_H = %d, %d" % (W, H)]
lines.append("local OBLASTS = { %s }" % ", ".join('"%s"' % n for n in oblast_names))
lines.append("local REGIONS = {")
total = 0
sil = rects(lambda x, y: lab[x, y] != 0)
total += len(sil)
for i, (name, o, _) in enumerate(regions, 1):
    def inside(x, y):
        if lab[x, y] != i:
            return False
        r, b = at(lab, x + 1, y), at(lab, x, y + 1)
        return r in (0, i) and b in (0, i)
    rs = rects(inside)
    if not rs:  # too small for the gap: draw it whole
        rs = rects(lambda x, y: lab[x, y] == i)
    total += len(rs)
    pts = [(x, y) for y in range(H) for x in range(W) if lab[x, y] == i]
    cx = sum(p[0] for p in pts) // len(pts)
    cy = sum(p[1] for p in pts) // len(pts)
    lines.append('    { name = "%s", oblast = %d, cx = %d, cy = %d, rects = "%s" },' % (name, o, cx, cy, pack(rs)))
lines.append("}")


def border(x, y):
    a = obl[x, y]
    return a != 0 and (at(obl, x + 1, y) not in (0, a) or at(obl, x, y + 1) not in (0, a))


edges = rects(border)
total += len(edges)
lines.append('local SILHOUETTE = "%s"' % pack(sil))
lines.append('local BORDERS = "%s"' % pack(edges))
lines.append("-- MAP END")
print("regions", len(regions), "rects", total, file=sys.stderr)

text = open(dst, encoding="utf-8").read()
text = re.sub(r"-- MAP BEGIN.*?-- MAP END", lambda m: "\n".join(lines), text, flags=re.S)
open(dst, "w", encoding="utf-8").write(text)
